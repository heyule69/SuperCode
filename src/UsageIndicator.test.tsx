// @vitest-environment happy-dom
import { act } from 'react';
import { createRoot } from 'react-dom/client';
import { afterEach, expect, it } from 'vitest';
import { UsageIndicator } from './UsageIndicator';
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const host = document.createElement('div');
document.body.append(host);
const root = createRoot(host);
afterEach(async () => { await act(async () => root.render(null)); });
it('updates the read-only context indicator and explains a missing capacity', async () => {
  await act(async () => root.render(<UsageIndicator usage={{ total: {}, last: {}, contextTokens: 12345, cumulative: false }}/>));
  const indicator = host.querySelector<HTMLElement>('.usage-trigger')!;
  expect(indicator.textContent).toBe('上下文 12.3K');
  expect(indicator.getAttribute('aria-label')).toBe('最近一次上下文 12,345 Token');
  expect(indicator.getAttribute('role')).toBe('img');
  await act(async () => indicator.focus());
  expect(host.querySelector('[role=tooltip]')?.textContent).toContain('已用 12k Token，上限暂未返回');
  expect(host.textContent).not.toContain('使用量暂未返回');
  await act(async () => root.render(<UsageIndicator usage={{ total: {}, last: {}, contextTokens: 24000, modelContextWindow: 128000 }}/>));
  expect(indicator.textContent).toBe('上下文 19%');
  expect(indicator.getAttribute('role')).toBe('meter');
  expect(indicator.getAttribute('aria-valuenow')).toBe('18.75');
  expect(indicator.getAttribute('aria-valuetext')).toBe('19% 已用（剩余 81%）');
});
it('shows the compact reference tooltip on hover and tracks growth and compaction with fractional fill', async () => {
  const render = async (contextTokens: number) => act(async () => root.render(<UsageIndicator contextWindow={475000} usage={{ total: { totalTokens: 9999999 }, last: {}, contextTokens, cumulative: false }}/>));
  await render(166000);
  await act(async () => host.querySelector('.usage-indicator')!.dispatchEvent(new MouseEvent('mouseover', { bubbles:true })));
  const tooltip = host.querySelector('[role=tooltip]')!;
  expect(tooltip.children).toHaveLength(2);
  expect(tooltip.textContent).toContain('35% 已用（剩余 65%）');
  expect(tooltip.textContent).toContain('已用 166k Token，共 475k');
  const meter = host.querySelector<HTMLElement>('[role=meter]')!;
  const ring = host.querySelector<HTMLElement>('.context-ring')!;
  expect(Number(meter.getAttribute('aria-valuenow'))).toBeCloseTo(34.947, 3);
  await render(300000); expect(ring.style.getPropertyValue('--context-percent')).toBe(`${300000/475000*100}%`);
  await render(21000); expect(Number(meter.getAttribute('aria-valuenow'))).toBeCloseTo(4.421, 3);
  await render(100); expect(Number(meter.getAttribute('aria-valuenow'))).toBeGreaterThan(0);
  expect(host.querySelector('[role=tooltip]')!.textContent).toContain('<1% 已用');
  await act(async () => host.querySelector('.usage-indicator')!.dispatchEvent(new MouseEvent('mouseout', { bubbles:true })));
  expect(host.querySelector('[role=tooltip]')).toBeNull();
});
it('uses the runtime capacity before a model fallback and keeps absent usage unknown', async () => {
  await act(async () => root.render(<UsageIndicator contextWindow={1000000} usage={{total:{},last:{},contextTokens:64000,modelContextWindow:128000}}/>));
  expect(host.querySelector('.usage-trigger')!.textContent).toBe('上下文 50%');
  await act(async () => root.render(<UsageIndicator contextWindow={475000}/>));
  const indicator = host.querySelector<HTMLElement>('.usage-trigger')!;
  await act(async () => indicator.focus());
  const tooltip = host.querySelector('[role=tooltip]')!;
  expect(tooltip.textContent).toContain('使用量暂未返回，共 475k');
  expect(indicator.getAttribute('aria-describedby')).toBe(tooltip.id);
  expect(indicator.hasAttribute('aria-valuenow')).toBe(false);
  expect(indicator.getAttribute('role')).toBe('img');
  expect(indicator.textContent).toBe('上下文 —');
  await act(async () => indicator.dispatchEvent(new KeyboardEvent('keydown', {key:'Escape',bubbles:true})));
  expect(host.querySelector('[role=tooltip]')).toBeNull();
  expect(indicator.hasAttribute('aria-describedby')).toBe(false);
  await act(async () => indicator.blur());
  await act(async () => indicator.focus());
  expect(host.querySelector('[role=tooltip]')).not.toBeNull();
});
it('does not open a context page or offer manual compression and stats actions on click or activation keys', async () => {
  await act(async () => root.render(<UsageIndicator usage={{total:{inputTokens:120000,outputTokens:4000},last:{},contextTokens:126000,modelContextWindow:128000,costUsd:2.5}}/>));
  const indicator = host.querySelector<HTMLElement>('.usage-trigger')!;
  expect(indicator.tagName).toBe('SPAN');
  expect(indicator.getAttribute('tabindex')).toBe('0');
  expect(host.querySelector('.context-ring')?.classList.contains('context-high')).toBe(true);
  await act(async () => {
    indicator.click();
    for (const key of ['Enter',' ']) indicator.dispatchEvent(new KeyboardEvent('keydown', {key,bubbles:true}));
  });
  expect(host.querySelector('[role=dialog]')).toBeNull();
  expect(host.querySelector('.usage-popover')).toBeNull();
  expect(host.querySelector('button,a,progress')).toBeNull();
  expect(indicator.hasAttribute('aria-expanded')).toBe(false);
  expect(indicator.hasAttribute('aria-haspopup')).toBe(false);
  expect(host.textContent).not.toContain('压缩上下文');
  expect(host.textContent).not.toContain('查看用量统计');
});
