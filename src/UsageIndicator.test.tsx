// @vitest-environment happy-dom
import { act } from 'react';
import { createRoot } from 'react-dom/client';
import { afterEach, expect, it, vi } from 'vitest';
import { UsageIndicator } from './UsageIndicator';
vi.mock('./api', () => ({ desktop: true }));
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const host = document.createElement('div');
document.body.append(host);
const root = createRoot(host);
afterEach(async () => { await act(async () => root.render(null)); });
it('updates visible tokens while running and explains a missing capacity without claiming missing usage', async () => {
  const props = { busy: true, compact: vi.fn(), openStats: vi.fn() };
  await act(async () => root.render(<UsageIndicator {...props} usage={{ total: {}, last: {}, contextTokens: 12345, cumulative: false }}/>));
  const button = host.querySelector<HTMLButtonElement>('.usage-trigger')!;
  expect(button.textContent).toBe('上下文 12.3K');
  await act(async () => button.click());
  expect(host.textContent).toContain('12,345');
  expect(host.textContent).toContain('已显示最近一次实际用量');
  expect(button.getAttribute('aria-label')).toBe('最近一次上下文 12,345 Token');
  expect(host.textContent).not.toContain('尚未提供上下文用量');
  await act(async () => root.render(<UsageIndicator {...props} busy={false} usage={{ total: {}, last: {}, contextTokens: 24000, modelContextWindow: 128000 }}/>));
  expect(button.textContent).toBe('上下文 19%');
  expect(host.querySelector('progress')?.value).toBe(19);
});
it('shows the compact reference tooltip on hover and tracks growth and compaction with fractional fill', async () => {
  const props = { busy: true, compact: vi.fn(), openStats: vi.fn(), contextWindow: 475000 };
  const render = async (contextTokens: number) => act(async () => root.render(<UsageIndicator {...props} usage={{ total: { totalTokens: 9999999 }, last: {}, contextTokens, cumulative: false }}/>));
  await render(166000);
  await act(async () => host.querySelector('.usage-indicator')!.dispatchEvent(new MouseEvent('mouseover', { bubbles:true })));
  const tooltip = host.querySelector('[role=tooltip]')!;
  expect(tooltip.textContent).toContain('背景信息窗口：35% 已用（剩余 65%）');
  expect(tooltip.textContent).toContain('已用 166k 标记，共 475k');
  const meter = host.querySelector<HTMLElement>('[role=meter]')!;
  expect(Number(meter.getAttribute('aria-valuenow'))).toBeCloseTo(34.947, 3);
  await render(300000); expect(meter.style.getPropertyValue('--context-percent')).toBe(`${300000/475000*100}%`);
  await render(21000); expect(Number(meter.getAttribute('aria-valuenow'))).toBeCloseTo(4.421, 3);
  await render(100); expect(Number(meter.getAttribute('aria-valuenow'))).toBeGreaterThan(0);
  expect(host.querySelector('[role=tooltip]')!.textContent).toContain('<1% 已用');
  await act(async () => host.querySelector('.usage-indicator')!.dispatchEvent(new MouseEvent('mouseout', { bubbles:true })));
  expect(host.querySelector('[role=tooltip]')).toBeNull();
});
it('uses the runtime capacity before a model fallback and keeps absent usage unknown', async () => {
  const props = { busy:false, compact:vi.fn(), openStats:vi.fn() };
  await act(async () => root.render(<UsageIndicator {...props} contextWindow={1000000} usage={{total:{},last:{},contextTokens:64000,modelContextWindow:128000}}/>));
  expect(host.querySelector('.usage-trigger')!.textContent).toBe('上下文 50%');
  await act(async () => root.render(<UsageIndicator {...props} contextWindow={475000}/>));
  const button = host.querySelector<HTMLButtonElement>('.usage-trigger')!;
  await act(async () => button.focus());
  expect(host.querySelector('[role=tooltip]')!.textContent).toContain('使用量暂未返回，共 475k');
  expect(host.querySelector('[role=meter]')!.hasAttribute('aria-valuenow')).toBe(false);
  expect(button.textContent).toBe('上下文 —');
  await act(async () => button.dispatchEvent(new KeyboardEvent('keydown', {key:'Escape',bubbles:true})));
  expect(host.querySelector('[role=tooltip]')).toBeNull();
});
